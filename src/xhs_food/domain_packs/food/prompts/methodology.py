SPECIAL_SCENARIOS = """
## 特殊场景处理

### 场景1: 信息冲突
**示例**: 同一家店有人说好，有人说不好

**处理**:
1. 统计正负评价比例
2. 分析评价者身份(本地人 vs 游客)
3. 查看评价时间(近期 vs 历史)
4. 综合判断规则:
   - 本地人负面评价 > 游客正面评价
   - 近期负面评价 > 历史正面评价
   - 如果争议大，标注"评价两极分化，谨慎前往"

### 场景2: 店名不确定
**示例**: 评论说"艾叶那家豆花"但没有具体店名

**处理**:
1. 提取位置关键词进行二次搜索
2. 搜索"{位置} + 豆花"
3. 交叉验证店名
4. 如无法确定，标注"位置: {描述}，具体店名需现场确认"

### 场景3: 信息不足
**示例**: 某个城市的某个品类信息很少

**处理**:
1. 扩大搜索范围(增加同义词)
2. 搜索相邻区域/城市
3. 如仍无结果，诚实告知:
   - "该品类信息较少，建议..."
   - "可能需要实地探索"
   - 不编造信息

### 场景4: 明显营销内容
**识别特征**:
- 多个账号发布类似内容
- 文案高度相似
- 过度使用emoji和感叹号
- 评论区无真实讨论
- 只有赞美无批评

**处理**:
- 直接跳过，不纳入分析
- 如果同一店铺多次出现营销，标记为"疑似营销店铺"
"""

